@pytest.mark.integration
def test_export_rejects_silent_and_out_of_bounds_source_content(tmp_path: Path) -> None:
    if not shutil.which("ffmpeg") or not shutil.which("ffprobe"):
        pytest.skip("FFmpeg is not available")
    media = MediaTools()
    source = tmp_path / "silent.mp4"
    media.run(
        [
            media.ffmpeg,
            "-hide_banner",
            "-loglevel",
            "error",
            "-y",
            "-f",
            "lavfi",
            "-i",
            "color=c=black:s=160x90:r=10:d=1",
            "-f",
            "lavfi",
            "-i",
            "anullsrc=r=48000:cl=mono:d=1",
            "-shortest",
            "-c:v",
            "mpeg4",
            "-c:a",
            "aac",
            str(source),
        ],
        "Creating silent test video",
    )
    silent = PackProject(
        title="Silent",
        authors=["Tester"],
        video_path=str(source),
        video_duration=10,
        segments=[Segment(0.1, 0.7, "Supposed line", ["Speaker"])],
    )
    with pytest.raises(RuntimeError, match="no audible content"):
        PackExporter(media).export(silent, tmp_path / "silent-output", create_zip=False)

    out_of_bounds = PackProject(
        title="Past EOF",
        authors=["Tester"],
        video_path=str(source),
        video_duration=10,
        segments=[Segment(2, 3, "Past the end", ["Speaker"])],
    )
    with pytest.raises(ValueError, match="after the video"):
        PackExporter(media).export(out_of_bounds, tmp_path / "eof-output", create_zip=False)
